#!/usr/bin/env python3
"""Dump, or load, the set of codepoints a font maps, as a list of hex ranges.

    python3 build/charset.py /path/to/seguisym.ttf > build/charsets/segoe-ui-symbol.txt

fill.py needs to know which codepoints Segoe UI Symbol covers, and Segoe UI
Symbol is a Microsoft font we cannot check in. Its character set is not
copyrightable, so we check that in instead: run this against the copy in
C:\\Windows\\Fonts (or wherever) and commit the output. Regenerate it when a
Windows release ships a new version of the font; the header records which
version the list came from.

The file is one range per line, inclusive, hex, with ``#`` comments. It is
the raw cmap -- controls, format characters and Private Use are all listed
if the font maps them. fill.py applies its own exclusions on top, so this
file stays a faithful record of what the font has.
"""

import argparse
import os
import sys


def load(path):
    """Return the set of codepoints listed in a charset file."""
    codepoints = set()
    with open(path, encoding="utf-8") as handle:
        for lineno, raw in enumerate(handle, 1):
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            first, _, last = line.partition("-")
            try:
                lo = int(first, 16)
                hi = int(last, 16) if last else lo
            except ValueError:
                sys.exit("{}:{}: not a hex range: {!r}".format(path, lineno, raw.rstrip()))
            if hi < lo:
                sys.exit("{}:{}: backwards range: {!r}".format(path, lineno, raw.rstrip()))
            codepoints.update(range(lo, hi + 1))
    return codepoints


def ranges(codepoints):
    """Collapse a set of codepoints into sorted inclusive (lo, hi) pairs."""
    out = []
    for cp in sorted(codepoints):
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return [tuple(pair) for pair in out]


def dump(font_path, out):
    try:
        from fontTools.ttLib import TTFont
    except ImportError:
        sys.exit("charset.py: fontTools is not installed (pip install fonttools)")

    font = TTFont(font_path)
    cmap = font.getBestCmap() or {}
    names = {}
    for record in font["name"].names:
        names.setdefault(record.nameID, record.toUnicode())

    out.write("# Character set of {!r}, {}\n".format(
        names.get(1, "?"), names.get(5, "unknown version")))
    out.write("# {} codepoints, from {}\n".format(len(cmap), os.path.basename(font_path)))
    out.write("# Generated by build/charset.py -- do not edit by hand.\n")
    for lo, hi in ranges(cmap):
        if lo == hi:
            out.write("{:04X}\n".format(lo))
        else:
            out.write("{:04X}-{:04X}\n".format(lo, hi))


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("font", help="font file to read the cmap of")
    parser.add_argument("-o", "--output", help="write here instead of stdout")
    args = parser.parse_args()

    if not os.path.isfile(args.font):
        sys.exit("charset.py: no such file: {}".format(args.font))

    if args.output:
        with open(args.output, "w", encoding="utf-8", newline="\n") as handle:
            dump(args.font, handle)
    else:
        dump(args.font, sys.stdout)


if __name__ == "__main__":
    main()
